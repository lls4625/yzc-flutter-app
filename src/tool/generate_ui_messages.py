"""Regenerate the canonical legacy UI-message adapter from official ARB keys.

Run before flutter gen-l10n after changing ARB messages. Never use this adapter
for textbook or server-authored content. Placeholder messages use generated APIs.
"""
import json
from pathlib import Path

root = Path(__file__).resolve().parents[1] / 'lib' / 'l10n'
source = json.loads((root / 'app_zh_Hans.arb').read_text())
base = dict(source, **{'@@locale': 'zh'})
(root / 'app_zh.arb').write_text(json.dumps(base, ensure_ascii=False, indent=2) + '\n')
for locale in ['zh_Hant', 'en', 'ja']:
    translated = json.loads((root / f'app_{locale}.arb').read_text())
    assert {k for k in source if not k.startswith('@')} == {k for k in translated if not k.startswith('@')}, locale

def dart_string(value):
    return "'" + value.replace('\\', '\\\\').replace("'", "\\'").replace('\n', '\\n').replace('$', '\\$') + "'"

lines = ["import 'package:flutter/widgets.dart';", "import 'l10n.dart';", "import 'ui_composite_messages.dart';", '',
         '/// Generated by tool/generate_ui_messages.py from canonical ARB messages.',
         '/// Only call for application-owned UI messages, never textbook content.',
         'String localizedUiMessage(BuildContext context, String message) => switch (message) {']
seen = set()
for key, text in source.items():
    if key.startswith('@') or source.get('@' + key, {}).get('placeholders') or text in seen:
        continue
    seen.add(text)
    lines.append(f'  {dart_string(text)} => context.l10n.{key},')
lines += ['  _ => localizedCompositeMessage(context, message),', '};', '']
(root / 'ui_messages.dart').write_text('\n'.join(lines))
