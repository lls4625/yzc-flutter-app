          r'$',
    ),
];

/// Titles generated by the in-memory demo, never titles supplied by a package.
String studyDemoTitle(BuildContext context, String title) {
  final match = RegExp(r'^(N[1-5]) · (.+) · (\d+)题$').firstMatch(title);
  if (match == null) return studyUi(context, title);
  return studyUi(
    context,
    '${match[1]} · ${studyUi(context, match[2]!)} · ${match[3]}题',
  );
}
