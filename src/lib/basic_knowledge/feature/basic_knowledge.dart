class _SeasonEffectPainter extends CustomPainter {
  const _SeasonEffectPainter({required this.season, required this.progress, required this.continuous});
  final String season;
  final double progress;
  final bool continuous;

  @override
  void paint(Canvas canvas, Size size) {
    final points = const [(.12, .08), (.42, .19), (.72, .05), (.25, .42), (.82, .37), (.56, .62), (.16, .75), (.76, .84)];
    final fade = continuous || progress <= .72
        ? 1.0
        : ((1 - progress) / .28).clamp(0.0, 1.0).toDouble();

    if (season == 'spring') {
      final appearance = continuous
          ? 1.0
          : Curves.easeOut.transform(
              (progress / .42).clamp(0.0, 1.0).toDouble(),
            );
      final center = Offset(size.width * .78, size.height * .18);
      final radius = size.shortestSide * .085 * appearance;
      final rayStart = radius + size.shortestSide * .035;
      final rayEnd = radius + size.shortestSide * .085;
      final directions = const [
        (0.0, -1.0),
        (.72, -.72),
        (1.0, 0.0),
        (.72, .72),
        (0.0, 1.0),
        (-.72, .72),
        (-1.0, 0.0),
        (-.72, -.72),
      ];
      final rayPaint = Paint()
        ..color = const Color(0xFFFFC94A).withValues(alpha: .88 * fade * appearance)
        ..strokeWidth = 2
        ..strokeCap = StrokeCap.round;
      for (final direction in directions) {
        canvas.drawLine(
          Offset(
            center.dx + direction.$1 * rayStart,
            center.dy + direction.$2 * rayStart,
          ),
          Offset(
            center.dx + direction.$1 * rayEnd,
            center.dy + direction.$2 * rayEnd,
          ),
          rayPaint,
        );
      }
      canvas.drawCircle(
        center,
        radius,
        Paint()..color = const Color(0xFFFFD65A).withValues(alpha: .92 * fade * appearance),
      );
      return;
    }

    if (season == 'autumn') {
      canvas.save();
      canvas.clipRect(Offset.zero & size);
      for (var i = 0; i < 3; i++) {
        final phase = (progress + i * .34) % 1;
        _drawWindGust(canvas, size, phase, fade, i);
      }
      canvas.restore();
      return;
    }

    for (var i = 0; i < points.length; i++) {
      final travel = continuous
          ? (progress + i * .13) % 1
          : (progress * (1.15 + i * .04)) % 1;
      final paint = Paint()..style = PaintingStyle.fill;
      if (season == 'summer') {
        final x = size.width * points[i].$1;
        final y = size.height * ((points[i].$2 + travel) % 1);
        paint.color = const Color(0xFFE3F2F7).withValues(alpha: .67 * fade);
        paint.strokeWidth = 1.5;
        canvas.drawLine(Offset(x, y), Offset(x - 4, y + 13), paint);
      } else if (season == 'winter') {
        final x = size.width * points[i].$1;
        final y = size.height * ((points[i].$2 + travel) % 1);
        paint.color = const Color(0xFFFFFFFF).withValues(alpha: .87 * fade);
        canvas.drawCircle(Offset(x, y), 2.2 + (i % 2), paint);
      }
    }
  }

  void _drawWindGust(Canvas canvas, Size size, double phase, double fade, int index) {
    final unit = size.shortestSide * (.045 + index * .004);
    final center = Offset(
      size.width * (1.18 - phase * 1.48),
      size.height * (.30 + phase * .42 + (index - 1) * .08),
    );
    final path = Path()
      ..moveTo(center.dx + unit * 3.1, center.dy - unit * 1.7)
      ..cubicTo(
        center.dx + unit * 2.2,
        center.dy - unit * 1.15,
        center.dx + unit * 1.15,
        center.dy - unit * .35,
        center.dx + unit * .35,
        center.dy + unit * .05,
      )
      ..cubicTo(
        center.dx - unit * .35,
        center.dy + unit * .42,
        center.dx - unit * .95,
        center.dy + unit * .12,
        center.dx - unit * .72,
        center.dy - unit * .38,
      )
      ..cubicTo(
        center.dx - unit * .48,
        center.dy - unit * .92,
        center.dx + unit * .42,
        center.dy - unit * .82,
        center.dx + unit * .52,
        center.dy - unit * .22,
      )
      ..cubicTo(
        center.dx + unit * .64,
        center.dy + unit * .48,
        center.dx - unit * .62,
        center.dy + unit * 1.02,
        center.dx - unit * 1.48,
        center.dy + unit * .98,
      )
      ..cubicTo(
        center.dx - unit * 2.25,
        center.dy + unit * .94,
        center.dx - unit * 2.72,
        center.dy + unit * .55,
        center.dx - unit * 2.42,
        center.dy + unit * .18,
      )
      ..cubicTo(
        center.dx - unit * 2.12,
        center.dy - unit * .16,
        center.dx - unit * 1.52,
        center.dy + unit * .08,
        center.dx - unit * 1.68,
        center.dy + unit * .48,
      )
      ..cubicTo(
        center.dx - unit * 1.86,
        center.dy + unit * .92,
        center.dx - unit * 2.78,
        center.dy + unit * 1.28,
        center.dx - unit * 3.52,
        center.dy + unit * 1.23,
      );
    canvas.save();
    canvas.translate(center.dx, center.dy);
    canvas.scale(.78, 1);
    canvas.translate(-center.dx, -center.dy);
    canvas.drawPath(
      path,
      Paint()
        ..color = const Color(0xFF315B59).withValues(alpha: .34 * fade)
        ..style = PaintingStyle.stroke
        ..strokeWidth = 4
        ..strokeCap = StrokeCap.round,
    );
    canvas.drawPath(
      path,
      Paint()
        ..color = const Color(0xFFF2F8F6).withValues(alpha: .68 * fade)
        ..style = PaintingStyle.stroke
        ..strokeWidth = 2.2
        ..strokeCap = StrokeCap.round,
    );
    canvas.restore();
  }

  @override
  bool shouldRepaint(covariant _SeasonEffectPainter oldDelegate) =>
      oldDelegate.progress != progress || oldDelegate.season != season || oldDelegate.continuous != continuous;
}

