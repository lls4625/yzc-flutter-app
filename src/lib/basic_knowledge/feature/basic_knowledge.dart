class _KnowledgeRubyText extends StatelessWidget {
  const _KnowledgeRubyText(
    this.text, {
    this.fontSize = 15,
    this.fontWeight = FontWeight.normal,
    this.color,
  });

  final String text;
  final double fontSize;
  final FontWeight fontWeight;
  final Color? color;

  @override
  Widget build(BuildContext context) {
    final resolvedColor = color ?? Theme.of(context).colorScheme.onSurfaceVariant;
    final baseStyle = TextStyle(
      fontFamilyFallback: const ['Hiragino Sans'],
      fontSize: fontSize,
      height: 1.55,
      fontWeight: fontWeight,
    );
    final matches = RegExp(r'!([^!\s()]+)\(([^)]*)\)').allMatches(text).toList();
    if (matches.isEmpty) {
      if (text.contains('https://')) {
        return SelectableText(text, style: baseStyle.copyWith(color: resolvedColor));
      }
      return Text(text, style: baseStyle.copyWith(color: resolvedColor));
    }

    final tokens = <Widget>[];
    void addPlain(String value) {
      for (final rune in value.runes) {
        tokens.add(Text(
          String.fromCharCode(rune),
          style: baseStyle.copyWith(color: resolvedColor),
        ));
      }
    }
    void addRuby(String surface, String reading) {
      tokens.add(Column(
        mainAxisSize: MainAxisSize.min,
        children: [
          Text(
            reading,
            style: TextStyle(
              fontFamilyFallback: const ['Hiragino Sans'],
              locale: const Locale('ja', 'JP'),
              fontSize: fontSize * 0.53,
              height: 1.05,
              color: resolvedColor,
            ),
          ),
          Text(
            surface,
            style: baseStyle.copyWith(
              fontFamily: 'Hiragino Sans',
              locale: const Locale('ja', 'JP'),
              color: resolvedColor,
            ),
          ),
        ],
      ));
    }

    var offset = 0;
    for (final match in matches) {
      addPlain(text.substring(offset, match.start));
      addRuby(match.group(1)!, match.group(2)!);
      offset = match.end;
    }
    addPlain(text.substring(offset));
    return Wrap(
      spacing: 0,
      runSpacing: 4,
      crossAxisAlignment: WrapCrossAlignment.end,
      children: tokens,
    );
  }
}
