class _TopicHero extends StatelessWidget {
  const _TopicHero({required this.presentation});

  final _TopicPresentation presentation;

  @override
  Widget build(BuildContext context) {
    final usesGrammarOverview = const {
      _TopicVisualKind.verbs,
      _TopicVisualKind.nouns,
      _TopicVisualKind.particles,
    }.contains(presentation.visualKind);
    if (usesGrammarOverview) {
      return _GrammarTopicHero(presentation: presentation);
    }
    return StudyCard(
      clipBehavior: Clip.antiAlias,
      child: Column(
        crossAxisAlignment: CrossAxisAlignment.start,
        children: [
          if (presentation.visualKind == _TopicVisualKind.demonstratives)
            _DemonstrativesVisual(presentation: presentation)
          else if (presentation.visualKind == _TopicVisualKind.family)
            _FamilyVisual(presentation: presentation)
          else if (presentation.visualKind == _TopicVisualKind.body)
            _BodyVisual(presentation: presentation)
          else if (presentation.visualKind == _TopicVisualKind.location)
            _LocationVisual(presentation: presentation)
          else if (presentation.visualKind == _TopicVisualKind.colors)
            _ColorsVisual(presentation: presentation)
          else if (presentation.visualKind == _TopicVisualKind.weather)
            _WeatherVisual(presentation: presentation)
          else if (presentation.visualKind == _TopicVisualKind.travelTransport)
            _TravelTransportVisual(accent: presentation.accent)
          else if (presentation.visualKind == _TopicVisualKind.foodCulture)
            _FoodCultureVisual(accent: presentation.accent)
          else if (presentation.visualKind == _TopicVisualKind.travelSafety)
            _TravelSafetyVisual(accent: presentation.accent)
          else if (presentation.assetPath != null)
            AspectRatio(
              aspectRatio: 16 / 9,
              child: Image.asset(
                presentation.assetPath!,
                fit: BoxFit.cover,
                cacheWidth: 960,
                semanticLabel: presentation.semanticLabel,
              ),
            )
          else
            _TopicConceptVisual(
              kind: presentation.visualKind,
              accent: presentation.accent,
            ),
          Padding(
            padding: const EdgeInsets.fromLTRB(18, 16, 18, 18),
            child: Column(
              crossAxisAlignment: CrossAxisAlignment.start,
              children: [
                Text(
                  presentation.eyebrow,
                  style: TextStyle(
                    color: presentation.accent,
                    fontSize: 13,
                    fontWeight: FontWeight.w700,
                    letterSpacing: .5,
                  ),
                ),
                const SizedBox(height: 5),
                Text(
                  presentation.summary,
                  style: const TextStyle(
                    fontSize: 17,
                    height: 1.45,
                    fontWeight: FontWeight.w600,
                  ),
                ),
                if (presentation.highlights.isNotEmpty) ...[
                  const SizedBox(height: 12),
